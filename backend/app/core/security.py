"""Token generation and verification for WebSocket and REST authentication.

This module provides a minimal, dependency-free token scheme suitable for the
single-user (guest) mode of CloudMind-Zome.  Real user tokens are deterministic
HMAC-SHA256 digests signed with ``SECRET_KEY``; the guest mode uses a token
derived from ``SECRET_KEY`` so it is not hardcoded but remains stable for a
given deployment.
"""

from __future__ import annotations

import hashlib
import hmac
import logging
from typing import Optional

from fastapi import Header, HTTPException, status
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.dependencies import SECRET_KEY
from app.models import User

logger = logging.getLogger(__name__)

# Well-known guest user.
GUEST_USER_ID = "00000000-0000-0000-0000-000000000000"
# Guest token is deterministic for a given SECRET_KEY but not hardcoded.
GUEST_TOKEN = hmac.new(
    SECRET_KEY.encode("utf-8"),
    b"cloudmind-guest-token-v1",
    hashlib.sha256,
).hexdigest()


def create_access_token(user_id: str) -> str:
    """Return a deterministic access token for *user_id*.

    The token is ``HMAC-SHA256(user_id, SECRET_KEY)`` rendered as hex.
    It can be verified without storing the token in the database.
    """
    return hmac.new(
        SECRET_KEY.encode("utf-8"),
        user_id.encode("utf-8"),
        hashlib.sha256,
    ).hexdigest()


async def verify_access_token(token: str, db: AsyncSession) -> Optional[User]:
    """Verify *token* and return the matching User, or ``None``.

    Accepts:
    - The deterministic guest token (single-user mode).
    - A valid HMAC-SHA256 token generated by :func:`create_access_token` for
      any existing user.
    """
    if not token or not isinstance(token, str):
        return None

    if hmac.compare_digest(token, GUEST_TOKEN):
        result = await db.execute(select(User).where(User.id == GUEST_USER_ID))
        user = result.scalar_one_or_none()
        if user:
            return user

        # Auto-create the canonical guest user so a fresh install still works.
        guest = User(
            id=GUEST_USER_ID,
            codename="guest",
            nickname="访客",
            password_hash=None,
            device_id="guest-device",
            role="guest",
        )
        db.add(guest)
        await db.commit()
        await db.refresh(guest)
        return guest

    # Non-guest token: compare against all existing users.  This is acceptable
    # because CloudMind-Zome intentionally stays single-user/small-scale and
    # does not introduce a dedicated token table.
    result = await db.execute(select(User.id))
    for (user_id,) in result.all():
        expected = create_access_token(user_id)
        if hmac.compare_digest(token, expected):
            user_result = await db.execute(select(User).where(User.id == user_id))
            return user_result.scalar_one_or_none()

    return None


async def require_auth_token(
    authorization: str | None = Header(None),
) -> str:
    """Validate the ``Authorization: Bearer <token>`` header for REST APIs.

    In single-user mode only the deterministic guest token is accepted.
    Raises ``HTTPException(401)`` if the header is missing or invalid.
    """
    if not authorization:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Missing Authorization header",
            headers={"WWW-Authenticate": "Bearer"},
        )

    scheme, _, token = authorization.partition(" ")
    if scheme.lower() != "bearer" or not token:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid Authorization header format. Expected 'Bearer <token>'",
            headers={"WWW-Authenticate": "Bearer"},
        )

    if not hmac.compare_digest(token, GUEST_TOKEN):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid token",
            headers={"WWW-Authenticate": "Bearer"},
        )

    return token
